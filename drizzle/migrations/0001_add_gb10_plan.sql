CREATE OR REPLACE FUNCTION public.plan_limit_bytes(_plan TEXT)
RETURNS BIGINT
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE _plan
    WHEN 'gb10' THEN 10::BIGINT * 1024^3
    WHEN 'gb20' THEN 20::BIGINT * 1024^3
    WHEN 'tb1'  THEN 1024::BIGINT^4
    WHEN 'tb2'  THEN 2::BIGINT * 1024^4
    ELSE 5::BIGINT * 1024^3
  END
$$;